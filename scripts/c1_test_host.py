"""Run selected C1 checks against an explicitly supplied external test context.

No .env fallback; no dev project access. Context contains disposable credentials
and must live outside the repository. Generated by the isolated smoke setup.
"""
import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
from sqlalchemy.engine import URL


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--context", type=Path, required=True)
    parser.add_argument("pytest_args", nargs=argparse.REMAINDER)
    args = parser.parse_args()
    expected = Path(r"C:\Users\ADMIN\.conda\envs\ras\python.exe").resolve()
    if Path(sys.executable).resolve() != expected:
        raise SystemExit("use Conda ras interpreter")
    c = json.loads(args.context.read_text(encoding="utf-8"))
    root = Path(c["dir"]).resolve()
    repo = Path(__file__).resolve().parents[1]
    if root == repo or repo in root.parents or not c["project"].startswith("rasc1"):
        raise SystemExit("external isolated C1 context required")
    command = ["docker", "compose", "--env-file", str(root / "empty.env"), "-p", c["project"], "-f", str(root / "compose.json")]
    address = subprocess.check_output(command + ["port", "db", "5432"], text=True).strip()
    port = int(address.rsplit(":", 1)[1])
    url = URL.create("postgresql+psycopg", username=c["dbuser"], password=c["password"], host="127.0.0.1", port=port, database="c1_control")
    env = os.environ.copy()
    env["RAS_TEST_DATABASE_ADMIN_URL"] = url.render_as_string(hide_password=False)
    env["RAS_C1_RUNTIME_PASSWORD"] = c["runtime_password"]
    env["RAS_C1_RECOVERY_PASSWORD"] = c["recovery_password"]
    env["RAS_DB__HOST"], env["RAS_DB__PORT"] = "127.0.0.1", str(port)
    env["RAS_DB__USER"],env["RAS_DB__PASSWORD"],env["RAS_DB__NAME"] = c["dbuser"],c["password"],"c1_control"
    env.pop("RAS_DATABASE_URL",None)
    with open(root / "test-last.log", "w", encoding="utf-8") as log:
        proc = subprocess.Popen([sys.executable,"-m","pytest",*args.pytest_args],cwd=repo,env=env,stdout=subprocess.PIPE,stderr=subprocess.STDOUT,text=True,encoding="utf-8",errors="replace")
        for line in proc.stdout:
            print(line,end="",flush=True)
            log.write(line)
        return proc.wait()


if __name__ == "__main__":
    sys.exit(main())
